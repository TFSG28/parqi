/** Teste ponto-em-polígono (ray casting) para um anel em [lon, lat]. */
function pointInRing(
    lon: number,
    lat: number,
    ring: number[][]
): boolean {
    let inside = false;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
        const [xi, yi] = ring[i];
        const [xj, yj] = ring[j];
        const intersect =
            yi > lat !== yj > lat &&
            lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
        if (intersect) {
            inside = !inside;
        }
    }
    return inside;
}

/** Açores/Madeira ficam no meio do Atlântico: bbox com margem é seguro (nunca inclui outro país). */
const ISLAND_MARGIN_DEG = 0.04; // ~4 km
const ISLAND_BOXES: { minLon: number; minLat: number; maxLon: number; maxLat: number }[] =
    PORTUGAL_MULTIPOLYGON.slice(1).map((polygon) => {
        const ring = polygon[0];
        let minLon = Infinity;
        let minLat = Infinity;
        let maxLon = -Infinity;
        let maxLat = -Infinity;
        for (const [lon, lat] of ring) {
            minLon = Math.min(minLon, lon);
            minLat = Math.min(minLat, lat);
            maxLon = Math.max(maxLon, lon);
            maxLat = Math.max(maxLat, lat);
        }
        return {
            minLon: minLon - ISLAND_MARGIN_DEG,
            minLat: minLat - ISLAND_MARGIN_DEG,
            maxLon: maxLon + ISLAND_MARGIN_DEG,
            maxLat: maxLat + ISLAND_MARGIN_DEG,
        };
    });

/**
 * Portugal real (fronteira Natural Earth): continente + Açores + Madeira.
 * O bbox de PORTUGAL_BOUNDS serve apenas de pré-filtro rápido; a precisão
 * vem do teste ponto-em-polígono (bloqueia Espanha, ex.: Huelva/Badajoz).
 * As ilhas usam bbox com margem (são território português isolado no Atlântico).
 */
export function isInsidePortugal(latitude: number, longitude: number): boolean {
    if (
        latitude < PORTUGAL_BOUNDS.minLat ||
        latitude > PORTUGAL_BOUNDS.maxLat ||
        longitude < PORTUGAL_BOUNDS.minLon ||
        longitude > PORTUGAL_BOUNDS.maxLon
    ) {
        return false;
    }
    // Continente: teste rigoroso de fronteira
    if (pointInRing(longitude, latitude, PORTUGAL_MULTIPOLYGON[0][0])) {
        return true;
    }
    // Açores + Madeira: bbox com margem
    return ISLAND_BOXES.some(
        (box) =>
            longitude >= box.minLon &&
            longitude <= box.maxLon &&
            latitude >= box.minLat &&
            latitude <= box.maxLat
    );
}

/** Todos os vértices da geometria têm de estar dentro de Portugal (linhas/polígonos não podem cruzar a fronteira). */
export function isGeometryInsidePortugal(geometry: ParkingGeometryInput): boolean {
    if (geometry.type === 'Point') {
        const [lon, lat] = geometry.coordinates;
        return isInsidePortugal(lat, lon);
    }
    if (geometry.type === 'LineString') {
        return geometry.coordinates.every(([lon, lat]) => isInsidePortugal(lat, lon));
    }
    return geometry.coordinates.every((ring) => ring.every(([lon, lat]) => isInsidePortugal(lat, lon)));
}
